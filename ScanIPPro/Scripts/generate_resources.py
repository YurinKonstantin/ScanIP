def write_resw(lang, data):
    base = Path(__file__).resolve().parent.parent / "Strings" / lang
    base.mkdir(parents=True, exist_ok=True)
    lines = [HEADER]
    for key in sorted(data.keys()):
        val = xml.escape(data[key])
        lines.append(f'  <data name="{key}" xml:space="preserve"><value>{val}</value></data>\n')
    lines.append("</root>\n")
    (base / "Resources.resw").write_text("".join(lines), encoding="utf-8")

